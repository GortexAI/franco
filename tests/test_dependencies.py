"""The dependency files stay consistent, so scanners see what really ships.

pyproject.toml holds the ranges a pip install accepts. requirements.in holds
the same ranges; requirements.txt is compiled from it by pip-compile, with
every package (and its dependencies) pinned and hashed. Dependabot and
Renovate can only scan and fix what is pinned, and Docker installs exactly
the lock.
"""

import re
import tomllib
from pathlib import Path

import pytest

packaging = pytest.importorskip("packaging")
from packaging.requirements import Requirement  # noqa: E402
from packaging.utils import canonicalize_name  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent


def _requirements(lines) -> dict[str, Requirement]:
    out = {}
    for line in lines:
        line = line.split("#", 1)[0].strip()
        if line:
            req = Requirement(line)
            out[canonicalize_name(req.name)] = req
    return out


def _pyproject() -> dict[str, Requirement]:
    data = tomllib.loads((ROOT / "pyproject.toml").read_text())
    return _requirements(data["project"]["dependencies"])


def _requirements_in() -> dict[str, Requirement]:
    return _requirements((ROOT / "requirements.in").read_text().splitlines())


def _lock() -> tuple[str, dict[str, str]]:
    text = (ROOT / "requirements.txt").read_text()
    pins = dict(re.findall(r"^([A-Za-z0-9_.-]+)==([^\s\;]+)", text, re.MULTILINE))
    return text, {canonicalize_name(k): v for k, v in pins.items()}


def test_requirements_in_lists_the_same_packages_as_pyproject():
    assert set(_requirements_in()) == set(_pyproject())


def test_lock_is_pip_compile_output_with_every_package_pinned_and_hashed():
    text, pins = _lock()
    assert "autogenerated by pip-compile" in text
    assert "requirements.in" in text.split("\n\n", 1)[0] + text[:600]
    blocks = re.split(r"\n(?=[A-Za-z0-9_.-]+==)", text.split("#\n", 2)[-1].strip())
    for block in blocks:
        if "==" in block:
            assert "--hash=sha256:" in block, block.splitlines()[0]
    assert len(pins) > len(_pyproject())   # dependencies of dependencies, too


def test_every_direct_dependency_is_locked_within_its_pyproject_range():
    _, pins = _lock()
    for name, req in _pyproject().items():
        assert name in pins, f"{name} is missing from requirements.txt"
        assert pins[name] in req.specifier, (
            f"requirements.txt pins {name}=={pins[name]}, outside pyproject's {req.specifier}")
